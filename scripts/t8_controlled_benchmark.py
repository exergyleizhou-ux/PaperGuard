def main() -> int:
    print(f"=== T8 controlled benchmark ===", file=sys.stderr)
    print(f"  model = {os.environ.get('PAPERGUARD_LLM_MODEL', 'default')}",
          file=sys.stderr)
    print(f"  base  = {os.environ.get('PAPERGUARD_LLM_BASE_URL', 'default')}",
          file=sys.stderr)
    print(f"  N = {len(HUMAN_SAMPLES)} human + {len(AI_SAMPLES)} AI",
          file=sys.stderr)

    results: list[dict] = []
    for i, text in enumerate(HUMAN_SAMPLES):
        print(f"  [human {i+1:2d}/{len(HUMAN_SAMPLES)}]", file=sys.stderr, flush=True)
        score, segs = compute_detection_score(text)
        results.append({
            "arm": "human", "idx": i, "score": score,
            "n_segments": len(segs),
            "segments": segs,
        })

    for i, text in enumerate(AI_SAMPLES):
        print(f"  [ai    {i+1:2d}/{len(AI_SAMPLES)}]", file=sys.stderr, flush=True)
        score, segs = compute_detection_score(text)
        results.append({
            "arm": "ai", "idx": i, "score": score,
            "n_segments": len(segs),
            "segments": segs,
        })

    out_path = Path("scripts/t8_controlled_benchmark_results.json")
    out_path.write_text(
        json.dumps({
            "model": os.environ.get("PAPERGUARD_LLM_MODEL", "default"),
            "base_url": os.environ.get("PAPERGUARD_LLM_BASE_URL", "default"),
            "results": results,
        }, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )

    # Print summary
    human_scores = [r["score"] for r in results
                    if r["arm"] == "human" and r["score"] is not None]
    ai_scores = [r["score"] for r in results
                 if r["arm"] == "ai" and r["score"] is not None]

    print(f"\n=== Score distributions ===", file=sys.stderr)
    print(f"  human:  n={len(human_scores)}  scores={human_scores}",
          file=sys.stderr)
    print(f"  ai:     n={len(ai_scores)}  scores={ai_scores}",
          file=sys.stderr)

    # LR+ at default threshold: score < -0.5 → SUSPICIOUS+
    if human_scores and ai_scores:
        h_fp = sum(1 for s in human_scores if s < -0.5)
        a_tp = sum(1 for s in ai_scores if s < -0.5)
        tpr = a_tp / len(ai_scores)
        fpr = h_fp / len(human_scores)
        lr = tpr / fpr if fpr > 0 else float("inf")
        print(f"\n=== LR+ at score < -0.5 (SUSPICIOUS tier) ===",
              file=sys.stderr)
        print(f"  TPR (AI flagged)    = {tpr:.2%} ({a_tp}/{len(ai_scores)})",
              file=sys.stderr)
        print(f"  FPR (human flagged) = {fpr:.2%} ({h_fp}/{len(human_scores)})",
              file=sys.stderr)
        print(f"  LR+ = {lr}", file=sys.stderr)

    print(f"\nWrote {out_path}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
